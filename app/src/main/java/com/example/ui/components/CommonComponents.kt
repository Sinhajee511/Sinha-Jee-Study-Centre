@Composable
fun SinhaBottomNavigation(
    currentRoute: String,
    onNavigate: (String) -> Unit
) {
    NavigationBar(
        containerColor = MaterialTheme.colorScheme.surface,
        tonalElevation = 8.dp
    ) {
        val items = listOf(
            NavigationItem("home", "Home", "होम", Icons.Default.Home),
            NavigationItem("class_selection", "Books", "किताबें", Icons.Default.AutoStories),
            NavigationItem("quiz/all/all", "Quiz", "क्विज़", Icons.Default.Quiz),
            NavigationItem("progress", "Progress", "प्रगति", Icons.Default.Equalizer),
            NavigationItem("profile", "Profile", "प्रोफ़ाइल", Icons.Default.Person)
        )

        items.forEach { item ->
            val isSelected = currentRoute.startsWith(item.route.substringBefore("/"))
            NavigationBarItem(
                selected = isSelected,
                onClick = { onNavigate(item.route) },
                icon = {
                    Icon(
                        imageVector = item.icon,
                        contentDescription = item.labelEn
                    )
                },
                label = {
                    Text(
                        text = item.labelHi,
                        fontSize = 11.sp,
                        fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal
                    )
                },
                colors = NavigationBarItemDefaults.colors(
                    selectedIconColor = ScholarPrimary,
                    selectedTextColor = ScholarPrimary,
                    indicatorColor = MaterialTheme.colorScheme.primaryContainer
                )
            )
        }
    }
}

private data class NavigationItem(
    val route: String,
    val labelEn: String,
    val labelHi: String,
    val icon: ImageVector
)
